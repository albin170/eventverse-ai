/**
 * Validates and parses an imported JSON event file.
 */
export function validateImportedPlan(jsonStr: string): {
  success: boolean;
  plan?: EventPlan;
  error?: string;
} {
  try {
    const raw = JSON.parse(jsonStr);
    const parsed = EventPlanSchema.safeParse(raw);

    if (!parsed.success) {
      const issue = parsed.error.issues[0];
      return {
        success: false,
        error: `Validation error at ${issue.path.join('.')}: ${issue.message}`,
      };
    }

    return {
      success: true,
      plan: parsed.data as EventPlan,
    };
  } catch (err) {
    return {
      success: false,
      error: `Invalid JSON format: ${err instanceof Error ? err.message : 'Unknown parsing error'}`,
    };
  }
}

/**
 * Triggers a browser download of a text/csv/json file.
 */
export function downloadFile(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

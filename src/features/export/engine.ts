/**
 * Escapes characters that could be interpreted as formulas in spreadsheet software
 * (CSV Formula Injection / CSV Injection mitigation).
 * Characters: =, +, -, @, tab, carriage return.
 */
export function sanitizeCsvField(val: unknown): string {
  if (val === null || val === undefined) return '""';
  let str = String(val).trim();

  // If starts with formula triggers, prepend a single quote
  if (/^[=+\-@\t\r]/.test(str)) {
    str = `'${str}`;
  }

  // Escape any existing double quotes by doubling them
  const escaped = str.replace(/"/g, '""');
  return `"${escaped}"`;
}

/**
 * Generates CSV content for Budget Items.
 */
export function generateBudgetCsv(items: BudgetItem[], currency: string): string {
  const headers = [
    'Item ID',
    'Item Name',
    'Category',
    'Pricing Type',
    'Unit Cost',
    `Estimated Total (${currency})`,
    'Status',
    'Priority',
    'Notes',
  ];

  const rows = items.map((item) => [
    sanitizeCsvField(item.id),
    sanitizeCsvField(item.name),
    sanitizeCsvField(item.category),
    sanitizeCsvField(item.isPerPerson ? 'Per Person' : 'Fixed'),
    sanitizeCsvField(item.unitCost ?? 'N/A'),
    sanitizeCsvField(item.estimatedCost),
    sanitizeCsvField(item.confirmed ? 'Confirmed Quote' : 'Estimated'),
    sanitizeCsvField(item.priority),
    sanitizeCsvField(item.notes ?? ''),
  ]);

  return [headers.join(','), ...rows.map((r) => r.join(','))].join('\r\n');
}

/**
 * Generates CSV content for Timeline Tasks.
 */
export function generateTasksCsv(tasks: TimelineTask[]): string {
  const headers = [
    'Task ID',
    'Title',
    'Description',
    'Due Date',
    'Priority',
    'Status',
    'Responsible Person',
    'Completion (%)',
    'Dependencies',
  ];

  const rows = tasks.map((task) => [
    sanitizeCsvField(task.id),
    sanitizeCsvField(task.title),
    sanitizeCsvField(task.description),
    sanitizeCsvField(task.dueDate),
    sanitizeCsvField(task.priority),
    sanitizeCsvField(task.status),
    sanitizeCsvField(task.responsiblePerson),
    sanitizeCsvField(task.completionPercentage),
    sanitizeCsvField(task.dependencies.join('; ')),
  ]);

  return [headers.join(','), ...rows.map((r) => r.join(','))].join('\r\n');
}

/**
 * Generates CSV content for Vendors.
 */
export function generateVendorsCsv(vendors: Vendor[]): string {
  const headers = [
    'Vendor ID',
    'Company Name',
    'Category',
    'Contact Name',
    'Email',
    'Phone',
    'Price Range',
    'Starting Est. Price',
    'Shortlisted',
    'Enquiry Status',
    'Sample Type',
  ];

  const rows = vendors.map((v) => [
    sanitizeCsvField(v.id),
    sanitizeCsvField(v.name),
    sanitizeCsvField(v.category),
    sanitizeCsvField(v.contactName),
    sanitizeCsvField(v.email),
    sanitizeCsvField(v.phone),
    sanitizeCsvField(v.priceRange),
    sanitizeCsvField(v.estimatedStartingPrice),
    sanitizeCsvField(v.isShortlisted ? 'Yes' : 'No'),
    sanitizeCsvField(v.enquiryStatus),
    sanitizeCsvField(v.isDemoSample ? 'DEMO Sample (Unverified)' : 'Real Provider'),
  ]);

  return [headers.join(','), ...rows.map((r) => r.join(','))].join('\r\n');
}

